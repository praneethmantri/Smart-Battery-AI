"""
Pydantic schemas for personalized battery charging recommendations.
Preserves existing plan and response models while adding structured
request/response schemas, recommendation modes, and safety indicators.
"""

from datetime import datetime
from enum import Enum
from typing import Optional, List
from pydantic import BaseModel, Field, ConfigDict


class RecommendationMode(str, Enum):
    """Supported operational modes for charging recommendations."""
    DELAYED_CHARGE = "DELAYED_CHARGE"
    CHARGE_NOW = "CHARGE_NOW"
    ALREADY_ABOVE_TARGET = "ALREADY_ABOVE_TARGET"
    CONSERVATIVE_CHARGE = "CONSERVATIVE_CHARGE"
    HIGH_TEMPERATURE_WARNING = "HIGH_TEMPERATURE_WARNING"
    INSUFFICIENT_DATA = "INSUFFICIENT_DATA"


class PredictionSource(str, Enum):
    """Origin of the expected unplug time prediction."""
    GLOBAL_BASELINE = "GLOBAL_BASELINE"
    PERSONALIZED = "PERSONALIZED"
    BLENDED = "BLENDED"
    RULE_BASED = "RULE_BASED"


class ConfidenceLevel(str, Enum):
    """Categorical confidence rating based on score and schedule variance."""
    HIGH = "HIGH"
    MEDIUM = "MEDIUM"
    LOW = "LOW"


class UserPreferences(BaseModel):
    """User-configurable parameters for charging recommendations."""
    target_soc: float = Field(80.0, ge=20.0, le=100.0, description="Target state of charge in percent")
    charger_type: str = Field("standard", description="Charger profile: 'slow', 'standard', 'fast'")
    charging_rate_override: Optional[float] = Field(None, gt=0.0, description="Custom charging rate in %/hour")
    buffer_minutes: float = Field(15.0, ge=0.0, description="Safety buffer before predicted unplug in minutes")
    allow_delay: bool = Field(True, description="Whether delayed charging strategy is allowed")


class RecommendationRequest(BaseModel):
    """Input payload to request a personalized charging recommendation."""
    user_id: int = Field(..., gt=0, description="ID of the user")
    current_battery_percent: float = Field(..., ge=0.0, le=100.0, description="Current battery percentage [0-100]")
    target_battery_percent: Optional[float] = Field(80.0, ge=20.0, le=100.0, description="Target battery percentage")
    plug_time: Optional[datetime] = Field(None, description="Timestamp when plugged in (defaults to now)")
    current_temperature: Optional[float] = Field(None, description="Current battery temperature in degrees Celsius")
    charger_type: Optional[str] = Field("standard", description="Charger speed profile: 'slow', 'standard', 'fast'")
    screen_usage_minutes: Optional[float] = Field(0.0, ge=0.0, description="Screen usage prior to plug-in")
    prediction_override: Optional[datetime] = Field(None, description="Manual unplug time override for testing/simulation")
    confidence_score_override: Optional[float] = Field(None, ge=0.0, le=1.0, description="Manual confidence score override")


class ChargingRecommendationOutput(BaseModel):
    """Structured result generated by the recommendation engine."""
    user_id: int = Field(..., description="ID of the user")
    prediction_source: str = Field(..., description="Source of unplug prediction: GLOBAL_BASELINE, PERSONALIZED, BLENDED, RULE_BASED")
    predicted_unplug_time: datetime = Field(..., description="Predicted unplug datetime")
    current_soc: float = Field(..., description="Battery percentage at plug-in")
    target_soc: float = Field(..., description="Target battery percentage")
    recommended_start_time: datetime = Field(..., description="Scheduled time when active charging should begin")
    estimated_finish_time: datetime = Field(..., description="Estimated time when battery reaches target SOC")
    estimated_charging_minutes: float = Field(..., ge=0.0, description="Estimated active charging duration in minutes")
    confidence_level: str = Field(..., description="Confidence category: HIGH, MEDIUM, LOW")
    confidence_score: float = Field(..., ge=0.0, le=1.0, description="Numerical confidence score [0.0, 1.0]")
    mode: str = Field(..., description="Recommendation mode: DELAYED_CHARGE, CHARGE_NOW, ALREADY_ABOVE_TARGET, CONSERVATIVE_CHARGE, etc.")
    recommendation_message: str = Field(..., description="Human-readable advisory message")
    reason: str = Field(..., description="Algorithmic rationale explaining the recommendation")
    warnings: List[str] = Field(default_factory=list, description="List of safety or thermal warnings")
    charging_rate_pct_per_hr: float = Field(..., gt=0.0, description="Effective charging rate applied (%/hr)")
    idle_holding_minutes: float = Field(0.0, ge=0.0, description="Duration battery rests before charging starts (minutes)")


# ==============================================================================
# Existing Legacy & ORM-Mapped Schemas (Preserved for Backward Compatibility)
# ==============================================================================

class RecommendationPlan(BaseModel):
    """Multi-phase breakdown used by dashboard and legacy endpoints."""
    mode: str = Field(..., description="Charging mode: 'optimized_delayed', 'standard_direct'")
    phase_1_fast_charge_until: Optional[datetime] = Field(None, description="When 80% SoC will be reached")
    hold_at_pct: float = Field(80.0, description="Holding threshold to avoid electrolyte stress")
    phase_2_topoff_start: Optional[datetime] = Field(None, description="When to resume charging to 100%")
    estimated_ready_time: Optional[datetime] = Field(None, description="When battery reaches target SoC")
    confidence_score: float = Field(..., ge=0.0, le=1.0, description="ML prediction confidence (0 to 1)")
    recommendation_message: Optional[str] = Field(None, description="Actionable recommendation message")


class RecommendationCreate(BaseModel):
    """Schema for persisting a recommendation to the database."""
    user_id: int = Field(..., gt=0, description="ID of the user")
    session_id: Optional[int] = None
    predicted_unplug_time: datetime
    recommended_start_time: datetime
    target_soc: float = Field(80.0, ge=20.0, le=100.0)
    recommendation_message: Optional[str] = None
    mode: Optional[str] = "optimized_delayed"
    confidence_score: Optional[float] = 0.0


class RecommendationResponse(BaseModel):
    """Standard API response for recommendation records."""
    id: Optional[int] = None
    session_id: Optional[int] = None
    user_id: int
    predicted_unplug_time: datetime
    recommended_start_time: Optional[datetime] = None
    target_soc: Optional[float] = 80.0
    recommendation_message: Optional[str] = None
    mode: Optional[str] = None
    confidence_score: Optional[float] = None
    created_at: Optional[datetime] = None

    # Enriched plan data for dashboard
    recommendation: Optional[RecommendationPlan] = None
    recommendation_output: Optional[ChargingRecommendationOutput] = None

    model_config = ConfigDict(from_attributes=True)


class CurrentStatusResponse(BaseModel):
    """Real-time charging state summary."""
    user_id: int
    active_session: bool
    current_phase: str
    current_battery_pct: float
    next_transition_time: Optional[datetime] = None
    predicted_unplug_time: Optional[datetime] = None


# ==============================================================================
# Smart Recommendation Workflow Schemas (POST /api/recommendations/{id}/generate)
# ==============================================================================

class SmartRecommendationRequest(BaseModel):
    """Input payload for automated ML prediction + recommendation generation."""
    current_battery_percent: float = Field(..., ge=0.0, le=100.0, description="Current battery percentage [0-100]")
    charger_type: Optional[str] = Field("standard", description="Charger profile: 'slow', 'standard', 'fast'")
    current_temperature: Optional[float] = Field(None, description="Battery temperature in °C at plug-in")
    estimated_charging_rate_percent_per_hour: Optional[float] = Field(None, gt=0.0, description="Optional custom charging rate override (%/hr)")
    preferred_target_soc: Optional[float] = Field(80.0, ge=20.0, le=100.0, description="Desired target battery percentage")
    wants_full_charge: Optional[bool] = Field(False, description="Explicit request for 100% full charge")
    minimum_required_soc: Optional[float] = Field(70.0, ge=20.0, le=100.0, description="Minimum acceptable SOC")
    allow_delayed_charging: Optional[bool] = Field(True, description="Whether delayed charging strategy is allowed")
    plug_time: Optional[datetime] = Field(None, description="Plug-in event timestamp (defaults to current time)")


class PredictionSummary(BaseModel):
    """Unplug time prediction summary embedded in smart recommendation output."""
    predicted_unplug_time: str = Field(..., description="Formatted unplug clock time (HH:MM)")
    prediction_source: str = Field(..., description="Prediction strategy: GLOBAL_BASELINE, BLENDED, PERSONALIZED, RULE_BASED")
    confidence_level: str = Field(..., description="Confidence rating: HIGH, MEDIUM, LOW")
    confidence_score: float = Field(..., ge=0.0, le=1.0, description="Numerical confidence score")
    history_count: int = Field(..., description="Historical session count")
    predicted_unplug_datetime: Optional[datetime] = Field(None, description="Full future unplug datetime")


class RecommendationDetail(BaseModel):
    """Charging schedule and guidance details embedded in smart recommendation output."""
    mode: str = Field(..., description="Recommendation mode: DELAYED_CHARGE, CHARGE_NOW, ALREADY_ABOVE_TARGET, etc.")
    current_soc: float = Field(..., description="Battery percentage at plug-in")
    target_soc: float = Field(..., description="Target battery percentage")
    recommended_start_time: str = Field(..., description="Scheduled start clock time (HH:MM)")
    estimated_finish_time: str = Field(..., description="Estimated completion clock time (HH:MM)")
    estimated_charging_minutes: float = Field(..., ge=0.0, description="Active charging duration in minutes")
    message: str = Field(..., description="Human-readable advisory message")
    reason: str = Field(..., description="Algorithmic rationale")
    warnings: List[str] = Field(default_factory=list, description="Thermal and safety warnings")
    recommended_start_datetime: Optional[datetime] = Field(None, description="Full scheduled start datetime")
    estimated_finish_datetime: Optional[datetime] = Field(None, description="Full estimated finish datetime")


class SmartRecommendationResponse(BaseModel):
    """Unified response returning coupled ML prediction and personalized recommendation."""
    user_id: int = Field(..., description="ID of the user")
    prediction: PredictionSummary
    recommendation: RecommendationDetail
    recommendation_id: Optional[int] = Field(None, description="Persisted Recommendation database ID")
    prediction_id: Optional[int] = Field(None, description="Persisted Prediction database ID")
    created_at: Optional[datetime] = Field(None, description="Persistence timestamp")

